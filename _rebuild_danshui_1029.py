def table(data, header=True):
    h = '<thead><tr><th>市场</th><th>规格</th><th>价格</th></tr></thead>' if header else '<thead><tr><th>市场</th><th>规格</th><th>价</th></tr></thead>'
    body = '\n'.join(d[0] for d in data)
    return f'<table>{h}<tbody>\n{body}\n      </tbody></table>'

