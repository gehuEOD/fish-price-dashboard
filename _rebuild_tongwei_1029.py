def esc_spec(sp):
    return sp.replace("<", "&lt;")

def row(market, spec, price, hl):
    price_s = "{:g}".format(price)  # 整数/小数自然格式：35 / 25.25 / 27.75
    if hl == "red":
        pv = '<td class="price"><b style="color:#dc2626">{}</b></td>'.format(price_s)
    elif hl == "bold":
        pv = '<td class="price"><b>{}</b></td>'.format(price_s)
    else:
        pv = '<td class="price">{}</td>'.format(price_s)
    return '        <tr><td>{}</td><td><span class="spec spec-s">{}</span></td>{}</tr>'.format(
        market, esc_spec(spec), pv)

def build_tbody(rows):
    # rows: list of (market, spec, price, hl)，已按价格降序
    return "<tbody>\n" + "\n".join(row(*r) for r in rows) + "\n      </tbody>"

