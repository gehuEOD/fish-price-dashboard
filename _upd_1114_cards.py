def balance(text):
    """精确标签统计：<tag 后必须跟空白或 >，避免 <thead> 计入 <th。"""
    return {t: len(re.findall(r"<" + t + r"(?=[\s>])", text)) - text.count("</" + t + ">")
            for t in ("section", "div", "table", "thead", "tbody", "tr", "td", "th", "b")}


