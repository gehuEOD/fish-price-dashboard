def balance(text):
    """精确标签统计：<tag 后必须跟空白或 >，避免 <thead> 计入 <th、<body>/<br> 计入 <b。"""
    return {t: len(re.findall(r"<" + t + r"(?=[\s>])", text)) - text.count("</" + t + ">")
            for t in ("section", "div", "table", "thead", "tbody", "tr", "td", "th", "b")}


def main():
    html = open(HTML, encoding="utf-8").read()
    if GUARD in html:
        print("[SKIP] 本批次卡片已插入，退出以防重复")
        return 0

    before = balance(html)
    assert html.count(ANCHOR) == 1, ("锚点", ANCHOR, html.count(ANCHOR))
    idx = html.find(ANCHOR)
    pos = html.rfind('<div class="card"', 0, idx)
    assert pos > 0, "未找到 card 开标签"
    html = html[:pos] + CARDS + html[pos:]
    print("[OK] 已插入 2 张新卡（鳜康泰 11-14 / 腾氏 ㊺ 11-12）")

    for old, new in CHIP_SUBS:
        assert html.count(old) == 1, ("chip", old[:46], html.count(old))
        html = html.replace(old, new, 1)
    print("[OK] chip 快览 2 处来源列举同步（🤖 批发价 chip 由 refresh_freshness.py 托管，未改动）")

    after = balance(html)
    assert before == after, f"标签配平差值变化：{before} → {after}"
    assert html.count(GUARD) == 1
    assert html.count("🐟 腾氏水产 · 鳜鱼塘头价（2026-11-12") == 1
    # #1 的 csub 不得出现会导致 V2 trend 误判的字串
    i_gui = html.find(GUARD)
    i_teng = html.find("🐟 腾氏水产 · 鳜鱼塘头价（2026-11-12")
    assert 0 < i_gui < i_teng, "两张新卡顺序异常"
    seg = html[i_gui:i_teng]
    csub = re.search(r'<div class="csub">(.*?)</div>', seg, re.S)
    assert csub, "未找到 #1 卡 csub"
    if csub:
        ctxt = csub.group(1)
        assert "下跌" not in ctxt and "上涨" not in ctxt and "未给涨跌" not in ctxt, \
            "csub 含 trend 触发词，会误判 V2 鳜鱼 KPI"
    open(HTML, "w", encoding="utf-8").write(html)
    print("[OK] 写盘完成 · 字节数", len(html.encode("utf-8")), "· 标签差值", after)
    return 0


