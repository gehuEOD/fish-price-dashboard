# ================= 标签精确配平 =================
def balance(s):
    for tag in ["div", "table", "thead", "tbody", "tr", "td", "th", "h3", "span", "a", "b"]:
        o = len(re.findall(r"<%s(?=[\s>])" % tag, s))
        c = len(re.findall(r"</%s>" % tag, s))
        assert o == c, ("标签不配平", tag, o, c)


