def is_relevant(it):
    blob = " ".join([it.get("视频标题",""), it.get("视频简介",""), it.get("视频标签","")])
    kw = it.get("关键词","")
    if EXCLUDE.search(blob):
        return False
    if PRICE_HARD.search(blob):
        return True
    # 弱信号且须含明确品种+价格语义才留
    if PRICE_SOFT.search(blob) and ("鳜" in blob or "鲈" in blob):
        # 排除纯科普/城市，上面 EXCLUDE 已挡；此处仅放行含具体价格数字或"卖鱼/产值"
        if re.search(r"\d+\s*(元|块|斤)|卖鱼|产值|出鱼", blob):
            return True
    return False

